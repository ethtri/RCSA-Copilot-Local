import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createInitial,seedScene,startOwnerRevision,sendAssessment,completeReview,sendChallenge,respond,askFollowup,assessmentProjection} from '../src/scripts/demo/model.js';
import {saveRiskResponse,setResponseStrategy,discardOptionalResponse,nextResponseRisk,responseComplete} from '../src/scripts/demo/responses.js';
import {responseWorkspace,applyResponseDraft} from '../src/scripts/demo/response-view.js';
import {assessmentView} from '../src/scripts/demo/assessment.js';
import {ensureOperations,saveDecision,decideRequest,decisionView} from '../src/scripts/demo/operations.js';
import {addOwnerRisk} from '../src/scripts/demo/upgrade-model.js';
import {beginScopeEdit,saveScope} from '../src/scripts/demo/scope-model.js';
import {revisionComparison} from '../src/scripts/demo/revision-comparison.js';

const data=JSON.parse(await readFile(new URL('../assets/data/workflow-demo.json',import.meta.url),'utf8'));
const owner=createInitial(data);
beginScopeEdit(owner);
owner.scopeDraft.owner='  JORDAN LEE  ';
assert.equal(saveScope(owner,data).ok,false);

const fields={name:'Reconciliation delay',cause:'A file is late.',event:'A balancing entry is missed.',harm:'Settlement is delayed.'};
const custom=addOwnerRisk(owner,data,fields,['test','test','unknown']);
assert(custom.ok);
assert.deepEqual(owner.risks[custom.riskId].sources,['test']);
assert.equal(owner.risks[custom.riskId].prior,null);

owner.selectedRisk='details';
const details=owner.risks.details;
const baseline=structuredClone(details.riskResponse);
assert(setResponseStrategy(owner,'details','mitigate'));
assert(responseComplete(owner,'details'));
assert(details.residualConfirmed);
assert(discardOptionalResponse(owner));
assert.deepEqual(details.riskResponse,baseline);

const requestFlow=createInitial(data);
requestFlow.selectedRisk='details';
assert(setResponseStrategy(requestFlow,'details','accept'));
assert(applyResponseDraft(data,requestFlow));
const requestPlan=requestFlow.risks.details.riskResponse;
requestPlan.decisionOwner='Payments committee';
assert(saveRiskResponse(requestFlow));
const acceptance=ensureOperations(requestFlow).decisions.details;
assert.equal(acceptance.status,'draft');
assert.equal(acceptance.owner,'Payments committee');
assert.equal(acceptance.monitoring,requestPlan.monitoring);
assert.match(decisionView(data,requestFlow),/Review your request/);
requestPlan.decisionOwner='Risk committee';
assert(saveRiskResponse(requestFlow));
assert.equal(acceptance.owner,'Risk committee');
assert(saveDecision(requestFlow,'details',{submit:true}).ok);
assert.match(decisionView(data,requestFlow),/Risk committee has the request/);
requestFlow.role='management';
assert(decideRequest(requestFlow,'details','approved',{decisionReason:'Limits and monitoring are adequate.',conditions:requestPlan.conditions,reviewDate:requestPlan.reviewDate}).ok);
requestFlow.role='first';
assert.match(decisionView(data,requestFlow),/Approved/);
requestPlan.conditions='Limit the approval to the next test sample.';
assert(saveRiskResponse(requestFlow));
assert.equal(requestFlow.operations.archivedDecisions.at(-1).status,'approved');
assert.equal(requestFlow.operations.decisions.details.status,'draft');

const responseFlow=createInitial(data);
responseFlow.selectedRisk='details';
assert.match(responseWorkspace(data,responseFlow),/Add an optional response/);
assert(!responseWorkspace(data,responseFlow).includes('data-field="riskResponse.strategy"'));
assert(!nextResponseRisk(responseFlow));
for(const id of ['details','cutoff']){
 const risk=responseFlow.risks[id];
 risk.residual={...risk.residual,likelihood:4,impact:4};
 risk.residualConfirmed=true;
}
assert.equal(nextResponseRisk(responseFlow).id,'details');
assert.match(responseWorkspace(data,responseFlow),/How will you respond/);
assert(setResponseStrategy(responseFlow,'details','mitigate'));
assert(applyResponseDraft(data,responseFlow));
assert(saveRiskResponse(responseFlow));
assert(responseFlow.risks.details.residualConfirmed,'A planned response preserves the confirmed rating.');
assert.match(responseWorkspace(data,responseFlow),/Action owner/);
assert.match(responseWorkspace(data,responseFlow),/Continue to next response/);
assert.equal(nextResponseRisk(responseFlow).id,'cutoff');
responseFlow.risks.cutoff.removed=true;
assert(!nextResponseRisk(responseFlow),'Removed risks must never block the next step.');
assert.match(assessmentView(data,responseFlow,'response'),/Step 5 of 6/);
responseFlow.role='second';
assert.match(assessmentView(data,responseFlow,'review'),/Independent review/);
assert(!responseWorkspace(data,responseFlow).includes('data-action="edit-response"'));

const flow=seedScene(data,'submitted');
flow.selectedRisk='unauthorized';
flow.question='Who owns the test?';
assert(sendChallenge(flow));
flow.role='first';flow.response='Assurance owns the test.';
assert(respond(flow));
flow.role='second';flow.reviewerRationale='When is it due?';
assert(askFollowup(flow));
assert.equal(flow.assessmentView,'');
assert.equal(flow.challengeStatus,'open');
flow.role='first';flow.response='November 28.';
assert(respond(flow));
flow.role='second';flow.assessmentView='return';flow.reviewerRationale='Update the action due date.';flow.returnTarget='unauthorized/response';
assert(completeReview(flow));
flow.role='first';assert(startOwnerRevision(flow,data));
assert.equal(sendAssessment(flow),false);
assert.equal(flow.revisionRequest.target,'unauthorized/response');

const action=ensureOperations(flow).actions.unauthorized;
const originalDue=action.due;
flow.action.due='2026-12-09';flow.action.owner='Payments assurance';
flow.action.evidence='Retain the complete urgent-route test sample.';
assert(saveRiskResponse(flow));
assert.equal(action.due,flow.action.due);
assert.equal(action.owner,flow.action.owner);
assert.equal(action.requiredEvidence,flow.action.evidence);
assert(action.events.at(-1).detail.includes(originalDue));
flow.revisionAnswer='Updated the action owner, date and test evidence.';
flow.handoff='Review the updated urgent-route testing commitment.';
assert(sendAssessment(flow));
const v2=assessmentProjection(flow,2);
assert.equal(v2.handoff,flow.handoff);
assert.equal(v2.revisionAnswer,flow.revisionAnswer);
assert(revisionComparison(flow,v2).includes('2026-12-09'));
assert.equal(flow.snapshots[0].action.due,originalDue);
console.log('PASS: owner-defined scope, independent roles, optional response, follow-up, required revision answer, linked work and frozen handoff.');
